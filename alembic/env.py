"""Alembic environment configuration.

Reads the database URL from application settings (``app.config``) so that
credentials are never hardcoded in ``alembic.ini``.
"""

from logging.config import fileConfig

from sqlalchemy import engine_from_config, pool

from alembic import context

# ── Alembic Config object ────────────────────────────────────────────────────
config = context.config

# ── Python logging from the .ini file ────────────────────────────────────────
if config.config_file_name is not None:
    # Keep loggers that already exist (e.g. the app's, when Alembic is run
    # in-process) working instead of silently disabling them.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

# ── Import application settings and metadata ─────────────────────────────────
from app.config import settings  # noqa: E402
from app.database import Base  # noqa: E402
import app.models  # noqa: E402, F401  (registers all models on Base.metadata)

# Wire the database URL from .env / environment variables into Alembic's
# config so that engine_from_config picks it up.  Alembic's config uses
# configparser interpolation, so "%" (from percent-encoded passwords) must be
# escaped as "%%".
if settings.database_url:
    config.set_main_option("sqlalchemy.url", settings.database_url.replace("%", "%%"))

# This is the MetaData Alembic will compare against the database when
# generating autogenerated migrations.  Importing ``Base`` ensures all
# models that subclass it are registered.
target_metadata = Base.metadata


# ── Offline migrations (SQL script generation) ───────────────────────────────

def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode.

    Configures the context with just a URL so no live DBAPI connection is
    required.  Calls to ``context.execute()`` emit SQL to the script output.
    """
    url = config.get_main_option("sqlalchemy.url") or settings.database_url
    if not url:
        raise RuntimeError(
            "DATABASE_URL is not set. Configure it in .env before running migrations."
        )
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


# ── Online migrations (live database) ────────────────────────────────────────

def run_migrations_online() -> None:
    """Run migrations in 'online' mode.

    Creates an Engine and associates a connection with the migration context.
    """
    if not settings.database_url:
        raise RuntimeError(
            "DATABASE_URL is not set. Configure it in .env before running migrations."
        )

    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
        )

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
